export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 9;
// Every glyph is followed by one empty column.
export const GLYPH_ADVANCE = 6;

export function hasGlyph(character) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, character);
}

// Width of a single line in game units at the given pixel scale.
export function measureText(text, unit = 2) {
  const characters = Array.from(text);
  if (characters.length === 0) {
    return 0;
  }
  return (characters.length * GLYPH_ADVANCE - 1) * unit;
}

// Greedy word wrap used by the dialogue box so lines never reflow while the
// typewriter effect reveals characters.
export function wrapText(text, maxUnits, unit = 2) {
  const lines = [];
  let current = '';
  for (const word of String(text).split(' ')) {
    const candidate = current ? `${current} ${word}` : word;
    if (measureText(candidate, unit) > maxUnits && current) {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }
  lines.push(current);
  return lines;
}

export function drawText(view, text, x, y, options = {}) {
  const {
    unit = 2, color = '#FFF5FC', alpha = 1, align = 'left',
    shadow = null,
  } = options;
  const lines = Array.isArray(text) ? text : [text];
  lines.forEach((line, index) => {
    const width = measureText(line, unit);
    let startX = x;
    if (align === 'center') {
      startX = x - width / 2;
    } else if (align === 'right') {
      startX = x - width;
    }
    const lineY = y + index * (GLYPH_HEIGHT + 1) * unit;
    if (shadow) {
      drawGlyphs(view, line, startX + unit, lineY + unit, unit, shadow, alpha);
    }
    drawGlyphs(view, line, startX, lineY, unit, color, alpha);
  });
}

function drawGlyphs(view, text, x, y, unit, color, alpha) {
  let cursor = x;
  for (const character of Array.from(text)) {
    const rows = GLYPHS[character] ?? GLYPHS[' '];
    for (let row = 0; row < rows.length; row += 1) {
      const pixels = rows[row];
      for (let column = 0; column < pixels.length; column += 1) {
        if (pixels[column] === '#') {
          view.rect(cursor + column * unit, y + row * unit, unit, unit, color, alpha);
        }
      }
    }
    cursor += GLYPH_ADVANCE * unit;
  }
}
